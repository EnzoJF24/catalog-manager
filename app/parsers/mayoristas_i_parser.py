"""
Parser for "Mayoristas I" supplier catalogs.
Generated by Crystal Reports, A4 layout with:
  - Col 0 (x<100):  product image (thumbnail)
  - Col 1 (~100-175): SKU / CÓD. ART.
  - Col 2 (~175-290): MARCA (brand)
  - Col 3 (~290-480): DESCRIPCIÓN
  - Col 4 (~480-595): price (Mayoristas I)
  - Category headers: full-width bold row between product groups
"""
from __future__ import annotations
import re
import io
from pathlib import Path
from typing import Optional

import fitz  # PyMuPDF
from PIL import Image

from app.parsers.base_parser import BaseParser
from app.models.product import Product, ProductImage, ProcessingSession
from app.logging_config.logger import get_logger

log = get_logger("mayoristas_i_parser")

# ─── Column x-boundaries (in PDF points, A4 = 595 wide) ──────────────────────
# Calibrated from real PDF inspection:
#   SKU  "ACCE03"      x0≈106
#   BRAND "ACCESORIOS" x0≈160
#   DESC  "BANDITAS..."x0≈246
#   PRICE "$"          x0≈448, amount x0≈456

COL_IMAGE_MAX_X  = 105.0
COL_SKU_MIN_X    = 100.0
COL_SKU_MAX_X    = 157.0
COL_BRAND_MIN_X  = 157.0
COL_BRAND_MAX_X  = 245.0
COL_DESC_MIN_X   = 245.0
COL_DESC_MAX_X   = 440.0   # trimmed 5 pts so the $ sign never falls into the description
COL_PRICE_MIN_X  = 440.0   # lowered from 445 → recovers $ signs at x≈443

PRICE_RE        = re.compile(r"\$\s*[\d.,]+")
# Fallback: Argentine-format number without $ (e.g. "131.928,30") — used when the $ falls outside the column
PRICE_RE_LOOSE  = re.compile(r"\d{1,3}(?:[.,]\d{3})+,\d{2}|\d+,\d{2}")
SKU_RE   = re.compile(r"^[A-Z]{1,6}\d{1,4}[A-Z0-9]{0,4}$")

# Minimum image dimensions to consider as a product image
MIN_IMG_WIDTH  = 25
MIN_IMG_HEIGHT = 25
MAX_IMG_WIDTH  = 300
MAX_IMG_HEIGHT = 300

# Y-gap (pts) that separates product groups from each other
PRODUCT_GROUP_GAP = 35.0


class MayoristasIParser(BaseParser):
    """
    Parser for Mayoristas I wholesale catalogs (Crystal Reports, A4).
    """

    SUPPLIER_NAME = "Mayoristas I"
    DETECTION_KEYWORDS = ["Mayoristas I", "CÓD. ART.", "MARCA", "DESCRIPCIÓN"]
    DETECTION_PATTERNS = [r"Mayoristas\s+I", r"Crystal Reports"]

    def __init__(self, pdf_path: Path, output_dir: Path):
        super().__init__(pdf_path, output_dir)
        self._doc: Optional[fitz.Document] = None
        # Products with a valid SKU whose price could not be extracted
        self._skipped_products: list[dict] = []

    def _open_doc(self) -> fitz.Document:
        if self._doc is None:
            self._doc = fitz.open(str(self.pdf_path))
        return self._doc

    def _close_doc(self):
        if self._doc:
            try:
                self._doc.close()
            except Exception:
                pass
            self._doc = None

    def __enter__(self):
        self._open_doc()
        return self

    def __exit__(self, *_):
        self._close_doc()

    # ─── BaseParser interface ─────────────────────────────────────────────────

    def validate_pdf(self) -> tuple[bool, str]:
        try:
            doc = self._open_doc()
            if doc.page_count == 0:
                return False, "The PDF has no pages."
            page0_text = doc[0].get_text("text")
            if not any(kw in page0_text for kw in self.DETECTION_KEYWORDS):
                return False, (
                    f"No detection keywords found on page 1 "
                    f"— this PDF may not belong to {self.SUPPLIER_NAME}."
                )
            return True, "OK"
        except Exception as e:
            return False, str(e)

    def detect_layout(self) -> dict:
        doc = self._open_doc()
        page = doc[0]
        words = page.get_text("words")
        has_images = len(page.get_images()) > 0
        page_width = page.rect.width
        page_height = page.rect.height
        return {
            "page_count": doc.page_count,
            "page_width_pts": page_width,
            "page_height_pts": page_height,
            "has_images": has_images,
            "word_count_p1": len(words),
            "supplier": self.SUPPLIER_NAME,
        }

    def extract_products(self, session: ProcessingSession) -> list[Product]:
        """
        Extract products and, as a side-effect, populate self._row_data_by_page
        with {page_num: [(sku, y_center), ...]} so that extract_images() can
        reuse this data without a second full parse pass (I1 fix).
        """
        doc = self._open_doc()
        session.total_pages = doc.page_count
        products: list[Product] = []
        current_category = "UNCATEGORIZED"
        # Populated here, consumed by extract_images — avoids double parse
        self._row_data_by_page: dict[int, list[tuple[str, float]]] = {}

        for page_num in range(doc.page_count):
            try:
                page = doc[page_num]
                page_products, row_data, current_category = self._parse_page(
                    page, page_num, current_category
                )
                products.extend(page_products)
                self._row_data_by_page[page_num] = row_data
                log.debug(
                    f"Page {page_num + 1}/{doc.page_count}: "
                    f"+{len(page_products)} products (cat={current_category})"
                )
            except Exception as e:
                msg = f"Page {page_num + 1} error: {e}"
                session.errors.append(msg)
                log.error(msg)
                continue

        session.products_found = len(products)

        if self._skipped_products:
            msg = (
                f"{len(self._skipped_products)} product(s) with a valid SKU discarded "
                f"because no price was detected (see logs for details)"
            )
            session.warnings.append(msg)
            log.warning(msg)
            for s in self._skipped_products:
                session.warnings.append(
                    f"  SKIPPED page {s['page']}: {s['sku']} — {s['desc'][:40]}"
                )

        return products

    def extract_images(self, session: ProcessingSession) -> list[ProductImage]:
        """
        Extract product images using the row-position data already built by
        extract_products() — no second parse pass (I1 fix).

        C3 fixes applied:
          - Iterate ALL rects for each xref (not just rects[0]).
          - Relaxed column threshold (+30 pts tolerance).
          - Lowered MIN_IMG size to 15px.
          - Log discard reason per image for diagnostics.
          - Keep best-confidence image per SKU.
        """
        doc = self._open_doc()
        product_images: list[ProductImage] = []
        total_found = 0
        total_matched = 0
        discard_log: dict[str, int] = {
            "too_small": 0, "wrong_column": 0, "no_row": 0,
            "low_confidence": 0, "save_error": 0,
        }

        row_data_by_page = getattr(self, "_row_data_by_page", {})

        # best_by_sku: keep highest-confidence ProductImage per SKU
        best_by_sku: dict[str, ProductImage] = {}

        for page_num in range(doc.page_count):
            try:
                page      = doc[page_num]
                row_data  = row_data_by_page.get(page_num, [])
                img_list  = page.get_images(full=True)
                total_found += len(img_list)

                for img_info in img_list:
                    xref = img_info[0]
                    # Iterate ALL rects for this xref on this page (C3 fix)
                    try:
                        rects = page.get_image_rects(xref)
                    except Exception:
                        continue
                    if not rects:
                        continue

                    for img_rect in rects:
                        result, reason = self._extract_image_with_bbox(
                            doc, page, page_num, xref, img_rect, row_data
                        )
                        if result:
                            total_matched += 1
                            # Keep the highest-confidence match per SKU
                            existing = best_by_sku.get(result.sku)
                            if existing is None or result.confidence > existing.confidence:
                                best_by_sku[result.sku] = result
                        else:
                            discard_log[reason] = discard_log.get(reason, 0) + 1
            except Exception as e:
                log.error(f"Image error on page {page_num}: {e}")

        product_images = list(best_by_sku.values())

        session.images_found    = total_found
        session.images_matched  = len(product_images)
        session.images_unmatched = total_found - total_matched

        # Update products with their image paths
        for p in self._products:
            pi = best_by_sku.get(p.sku)
            if pi:
                p.image_path        = pi.file_path
                p.image_confidence  = pi.confidence

        log.info(
            f"Images: {total_found} found, {len(product_images)} matched, "
            f"{total_found - total_matched} rejected "
            f"(column={discard_log.get('wrong_column',0)}, "
            f"size={discard_log.get('too_small',0)}, "
            f"no_row={discard_log.get('no_row',0)}, "
            f"low_conf={discard_log.get('low_confidence',0)})"
        )
        return product_images

    # ─── Internal parsing helpers ─────────────────────────────────────────────

    def _parse_page(
        self, page: fitz.Page, page_num: int, current_category: str
    ) -> tuple[list[Product], list[tuple[str, float]], str]:
        """
        Parse a single page.
        Returns (products, row_data, updated_category).
        row_data is [(sku, y_center), ...] — reused by extract_images() to avoid
        a second parse pass (I1 fix).
        """
        groups   = self._cluster_words_into_product_groups(page)
        products = []
        row_data = []

        for grp_y, grp_words in groups:
            cat = self._try_extract_category(grp_words)
            if cat:
                current_category = cat
                continue

            product = self._try_extract_product(grp_words, current_category, page_num)
            if product:
                product.row_y = grp_y
                products.append(product)
                row_data.append((product.sku, grp_y))

        return products, row_data, current_category

    def _cluster_words_into_product_groups(
        self, page: fitz.Page
    ) -> list[tuple[float, list]]:
        """
        Cluster ALL words into product-level groups.
        Multi-line descriptions (e.g. y=177 and y=187) belong to the SAME product.
        Products are separated by gaps > PRODUCT_GROUP_GAP pts.

        Returns list of (anchor_y, all_words_in_group).
        anchor_y = y of the main product row (the row with SKU + price).
        """
        words = page.get_text("words")
        if not words:
            return []

        words = sorted(words, key=lambda w: (w[1], w[0]))

        # Step 1: thin-cluster into single-line rows
        fine_rows: list[tuple[float, list]] = []
        cur_y = None
        cur_words = []
        for w in words:
            yc = (w[1] + w[3]) / 2
            if cur_y is None:
                cur_y, cur_words = yc, [w]
            elif abs(yc - cur_y) <= 6.0:
                cur_words.append(w)
                cur_y = sum((ww[1] + ww[3]) / 2 for ww in cur_words) / len(cur_words)
            else:
                fine_rows.append((cur_y, sorted(cur_words, key=lambda ww: ww[0])))
                cur_y, cur_words = yc, [w]
        if cur_words:
            fine_rows.append((cur_y, sorted(cur_words, key=lambda ww: ww[0])))

        # Step 2: merge fine rows into product groups based on y-gap
        groups: list[tuple[float, list]] = []
        grp_y = None
        grp_words = []
        grp_anchor = None

        for row_y, row_words in fine_rows:
            if grp_y is None:
                grp_y, grp_words, grp_anchor = row_y, list(row_words), row_y
            elif (row_y - grp_y) <= PRODUCT_GROUP_GAP:
                # Same product group: merge
                grp_words.extend(row_words)
                # Update anchor to last y seen (keeps close)
                grp_y = row_y
            else:
                # New group
                if grp_words:
                    groups.append((grp_anchor, sorted(grp_words, key=lambda ww: (ww[1], ww[0]))))
                grp_y, grp_words, grp_anchor = row_y, list(row_words), row_y

        if grp_words:
            groups.append((grp_anchor, sorted(grp_words, key=lambda ww: (ww[1], ww[0]))))

        return groups

    def _try_extract_category(self, row_words: list) -> Optional[str]:
        """
        Detect category header groups.
        In this PDF, category headers are large bold text centered on the page,
        with no SKU (x≈106) and no price (x≈448).
        Example: "ACCESORIOS" at x0=228, y=113
        """
        if not row_words:
            return None

        words_text = [w[4].strip() for w in row_words if len(w[4].strip()) > 1]
        if not words_text:
            return None

        full_text = " ".join(words_text).strip()

        # Must not contain a price pattern
        if PRICE_RE.search(full_text):
            return None

        # Must not have words in the SKU column (x 100-157)
        has_sku_col_word = any(
            COL_SKU_MIN_X <= w[0] < COL_SKU_MAX_X for w in row_words
        )
        if has_sku_col_word:
            return None

        # Must not have words in price column
        has_price_col_word = any(w[0] >= COL_PRICE_MIN_X for w in row_words)
        if has_price_col_word:
            return None

        # Category text should be uppercase and not a SKU
        if not full_text.isupper():
            return None

        if any(SKU_RE.match(t) for t in words_text):
            return None

        # Should span the middle area of the page (centered text)
        x_min = min(w[0] for w in row_words)
        x_max = max(w[2] for w in row_words)
        x_center = (x_min + x_max) / 2
        page_center = 297.5  # A4 / 2

        # Category headers are roughly centered (within 120pts of page center)
        if abs(x_center - page_center) > 150:
            return None

        if len(full_text) < 3:
            return None

        return full_text

    def _try_extract_product(
        self, row_words: list, category: str, page_num: int
    ) -> Optional[Product]:
        """
        Extract a product from a group of words.
        Price strategy:
          1. Look for PRICE_RE ($ + digits) in the PRICE column (x >= COL_PRICE_MIN_X=440)
          2. Fallback: look for an Argentine-format number (no $) in the PRICE column
          3. Valid SKU but no price found → log it as skipped
        """
        if not row_words:
            return None

        sku_words   = [w for w in row_words if COL_SKU_MIN_X  <= w[0] < COL_SKU_MAX_X]
        brand_words = [w for w in row_words if COL_BRAND_MIN_X <= w[0] < COL_BRAND_MAX_X]
        desc_words  = [w for w in row_words if COL_DESC_MIN_X  <= w[0] < COL_DESC_MAX_X]
        price_words = [w for w in row_words if w[0] >= COL_PRICE_MIN_X]

        if not sku_words:
            return None

        sku_text   = self._normalize_sku(" ".join(w[4] for w in sku_words))
        brand_text = self._normalize_text(" ".join(w[4] for w in brand_words))
        desc_text  = self._normalize_text(" ".join(w[4] for w in desc_words))

        if not SKU_RE.match(sku_text):
            return None

        price = 0.0
        price_text = " ".join(w[4] for w in price_words)

        # Attempt 1: primary regex with $
        m = PRICE_RE.search(price_text)
        if m:
            price = self._parse_price(m.group())

        # Attempt 2: fallback — Argentine-format number without $ (e.g. "131.928,30")
        if price <= 0:
            m2 = PRICE_RE_LOOSE.search(price_text)
            if m2:
                price = self._parse_price(m2.group())
                if price > 0:
                    log.debug(
                        f"[FALLBACK PRICE] page {page_num+1} SKU={sku_text} "
                        f"raw='{price_text.strip()}' → {price}"
                    )

        # Attempt 3: search the WHOLE group (the $ may have landed in the description)
        if price <= 0:
            all_text = " ".join(w[4] for w in row_words)
            m3 = PRICE_RE.search(all_text) or PRICE_RE_LOOSE.search(all_text)
            if m3:
                price = self._parse_price(m3.group())
                if price > 0:
                    log.warning(
                        f"[PRICE RESCUED full-scan] page {page_num+1} SKU={sku_text} "
                        f"→ {price}"
                    )

        if price <= 0:
            log.error(
                f"[SKIPPED] page {page_num+1} SKU={sku_text} desc='{desc_text[:40]}' "
                f"— no price found. price_raw='{price_text}'"
            )
            self._skipped_products.append({
                "page":     page_num + 1,
                "sku":      sku_text,
                "desc":     desc_text,
                "price_raw": price_text,
                "reason":   "price not detected",
            })
            return None

        # Brand is honest data: empty if the supplier's PDF didn't specify it.
        # No fallback to category — brand and category are distinct concepts
        # (manufacturer vs product type). Presentation layers handle empty
        # brands gracefully (PDF omits the line, UI shows a "—" placeholder).
        return Product(
            sku=sku_text,
            brand=brand_text,
            description=desc_text,
            price_original=price,
            category=category,
            page_num=page_num,
        )

    def _extract_image_with_bbox(
        self,
        doc: fitz.Document,
        page: fitz.Page,
        page_num: int,
        xref: int,
        img_rect,
        row_data: list[tuple[str, float]],
    ) -> tuple[Optional[ProductImage], str]:
        """
        Extract a single image rect, match to nearest product row, save to disk.
        Returns (ProductImage, "") on success or (None, discard_reason) on failure.

        C3 fixes:
          - Caller already iterates all rects; this processes one rect at a time.
          - Column threshold relaxed by 30 pts.
          - MIN size lowered to 15 px.
          - Returns discard reason for diagnostics.
        """
        img_x_center = (img_rect.x0 + img_rect.x1) / 2
        img_y_center = (img_rect.y0 + img_rect.y1) / 2
        img_width    = img_rect.x1 - img_rect.x0
        img_height   = img_rect.y1 - img_rect.y0

        # Column filter: left column + 30 pt tolerance
        if img_x_center > COL_IMAGE_MAX_X + 30:
            return None, "wrong_column"

        # Size filter: 15 px min, 300 px max
        if img_width < 15 or img_height < 15 or img_width > MAX_IMG_WIDTH or img_height > MAX_IMG_HEIGHT:
            return None, "too_small"

        if not row_data:
            return None, "no_row"

        best_sku  = None
        best_dist = float("inf")
        for sku, row_y in row_data:
            dist = abs(img_y_center - row_y)
            if dist < best_dist:
                best_dist = dist
                best_sku  = sku

        confidence = max(0.0, 1.0 - (best_dist / 80.0))
        if confidence < 0.1 or best_sku is None:
            return None, "low_confidence"

        # One canonical file per SKU — enables reuse across re-imports
        out_path = self.output_dir / f"{best_sku}.png"

        # Image already on disk: skip extraction entirely (no I/O cost on re-import)
        if out_path.exists():
            return ProductImage(
                sku=best_sku,
                file_path=out_path,
                page_num=page_num,
                bbox=(img_rect.x0, img_rect.y0, img_rect.x1, img_rect.y1),
                width_px=max(1, int(img_rect.x1 - img_rect.x0)),
                height_px=max(1, int(img_rect.y1 - img_rect.y0)),
                confidence=round(confidence, 3),
            ), ""

        try:
            base_image = doc.extract_image(xref)
            img_bytes  = base_image["image"]

            pil_img = Image.open(io.BytesIO(img_bytes))
            w_px, h_px = pil_img.size

            if w_px < 15 or h_px < 15:
                return None, "too_small"

            if pil_img.mode not in ("RGB", "RGBA"):
                pil_img = pil_img.convert("RGB")

            pil_img.save(str(out_path), "PNG")

            return ProductImage(
                sku=best_sku,
                file_path=out_path,
                page_num=page_num,
                bbox=(img_rect.x0, img_rect.y0, img_rect.x1, img_rect.y1),
                width_px=w_px,
                height_px=h_px,
                confidence=round(confidence, 3),
            ), ""
        except Exception as e:
            log.warning(f"  Error saving image (xref={xref}): {e}")
            return None, "save_error"

    def __del__(self):
        self._close_doc()   # fallback: close if context manager was not used
